"""SQLite connection helper (issues #3 and #73).

The mock B2B-SaaS data generated by `scripts/generate_data.py` lives in a
SQLite database at `data/app.db` (gitignored). Aggregation/query code (this
issue's generator and later issues' `queries.py` / server state) all open
the database through this helper so connection settings — row factory,
foreign-key enforcement, busy timeout — are defined in exactly one place.

Issue #73 adds the sandbox half: uploads and samples live as isolated
per-dataset files under repo-root `data/sandboxes/<id>.db`, and the single
active one is resolved from the `DB_PATH` environment variable (empty
means no active DB), with the issue #75 in-memory dataset registry
(`agent/datasets.py`, moved by `POST /data/active`) winning when set.
`connect()` defaults to that active path so existing callers need no
edits; `connect_ro()` opens the active path read-only so queries can
never escape their sandbox.

Stdlib only: `sqlite3`, `os` and `pathlib`, so importing this module never
touches the agent's model dependencies and works under the bare system
interpreter.
"""

import os
import sqlite3
from pathlib import Path

# Resolved from this file's location, never from the cwd, so every entrypoint
# (script, test, server) targets the same repo-root `data/app.db` no matter
# where it is launched from.
DEFAULT_DB_PATH = Path(__file__).resolve().parents[1] / "data" / "app.db"

# Home of the per-dataset sandbox files (`agent/sandbox.py` writes
# `<id>.db` here); same from-`__file__` anchoring as DEFAULT_DB_PATH.
SANDBOX_DIR = Path(__file__).resolve().parents[1] / "data" / "sandboxes"

# Fallback defaults for the issue #79 datasource vars, mirrored from
# agent/config.py's registry rows (the env-contract tests pin them equal).
# DATASOURCE_URL names an alternate source (empty = local SQLite path
# resolution as today); DATASOURCE_RO guards the boot (agent/server.py
# refuses to start on any non-read-only spelling); SQL_TIMEOUT_S bounds
# the sqlite connect timeout.
_DATASOURCE_URL_DEFAULT = ""
_DATASOURCE_RO_DEFAULT = "1"
_SQL_TIMEOUT_S_DEFAULT = "5.0"

# Spellings that count as read-only for DATASOURCE_RO (case-insensitive,
# whitespace-stripped); anything else — including "0" or empty — means
# "not read-only" and server.py refuses to boot.
_READONLY_VALUES = ("1", "true", "yes")


def get_datasource_url():
    """Alternate datasource URL from DATASOURCE_URL (issue #79).

    Empty (the default) means local SQLite path resolution as today; a
    non-empty value is validated for non-blankness only — Postgres
    wiring is out of scope, SQLite remains the engine."""
    return os.getenv("DATASOURCE_URL", _DATASOURCE_URL_DEFAULT)


def is_readonly():
    """True when DATASOURCE_RO holds a read-only spelling (issue #79).

    Unset boots fine (the default is read-only); server.py — not this
    library helper — owns the fail-fast refusal, so tests keep
    connecting freely."""
    raw = os.getenv("DATASOURCE_RO", _DATASOURCE_RO_DEFAULT)
    return (raw or "").strip().lower() in _READONLY_VALUES


def _sql_timeout_s():
    """sqlite connect timeout in seconds from SQL_TIMEOUT_S (issue #79).

    Non-numeric, empty or non-positive values fall back to the default
    instead of failing the connection."""
    raw = os.getenv("SQL_TIMEOUT_S", _SQL_TIMEOUT_S_DEFAULT)
    if not raw or not raw.strip():
        return float(_SQL_TIMEOUT_S_DEFAULT)
    try:
        value = float(raw.strip())
    except (TypeError, ValueError):
        return float(_SQL_TIMEOUT_S_DEFAULT)
    if not value > 0:
        return float(_SQL_TIMEOUT_S_DEFAULT)
    return value


def _registry_active_path():
    """Active sandbox path from the issue #75 in-memory registry (None when
    no dataset is active or the registry module is unavailable). The
    import rides inside the function — with the dual package/script idiom
    the rest of the agent uses — so `db.py` stays import-cycle-free
    (`datasets.py` itself is stdlib-only and never imports back). Any
    registry failure reads as "no active dataset" and falls through to
    the `DB_PATH` path below, never 500ing a connection."""
    try:
        try:  # package-style entry (import agent.db from the repo root)
            from agent import datasets
        except ModuleNotFoundError:  # script-style (import db from agent/)
            import datasets  # type: ignore[no-redef]
    except ImportError:
        return None
    try:
        return datasets.active_path()
    except Exception:  # noqa: BLE001 - registry trouble means "no active"
        return None


def get_active_path():
    """Resolve the active sandbox database from `DB_PATH` (issue #73).

    Returns `Path(DB_PATH)` when the variable holds a non-blank value —
    relative spellings such as `./data/sandboxes/t1.db` stay relative, so
    they resolve against the caller's cwd exactly as written — and None
    when it is unset, empty or whitespace-only (no active DB). Never
    creates files or directories; a missing file simply fails when a
    connection to it is opened.
    """
    raw = os.getenv("DB_PATH", "")
    if raw is None or not raw.strip():
        return None
    return Path(raw)


def connect(db_path=None, *, readonly=False):
    """Open a connection to the app database.

    db_path: filesystem path of the database; when None (the default) the
        active issue #75 dataset is used if one is set, else the active
        `DB_PATH` sandbox if one is set, else DEFAULT_DB_PATH.
    readonly: open with SQLite's `mode=ro` URI so writes fail loudly instead
        of silently creating a second database file.

    Returns a `sqlite3.Connection` whose rows are `sqlite3.Row` (name-based
    access), with `PRAGMA foreign_keys = ON` (SQLite disables FK enforcement
    per connection by default) and the SQL_TIMEOUT_S busy timeout so concurrent readers
    during a generation run queue instead of erroring.
    """
    if db_path is None:
        db_path = _registry_active_path()
        if db_path is None:
            db_path = get_active_path()
    path = Path(db_path) if db_path is not None else DEFAULT_DB_PATH
    if readonly:
        conn = sqlite3.connect(
            f"file:{path}?mode=ro", uri=True, timeout=_sql_timeout_s()
        )
    else:
        conn = sqlite3.connect(str(path), timeout=_sql_timeout_s())
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def connect_ro(path=None):
    """Open the active sandbox read-only (issue #73).

    path: explicit database file; when None the active `DB_PATH` sandbox is
    used (falling back to DEFAULT_DB_PATH when no active DB is set). Opens
    with SQLite's `mode=ro` URI — writes raise instead of mutating — with
    the same row-factory/pragma/timeout settings as `connect()`.
    """
    return connect(path, readonly=True)
